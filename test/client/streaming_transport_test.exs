defmodule SimpleGrpc.Client.StreamingTransportTest do
  use ExUnit.Case, async: false

  alias SimpleGrpc.Registry

  defmodule StreamingServer do
    use SimpleGrpc.Server,
      server_file: "priv/protos/streaming/streaming_service.proto"

    def unary_call(req, _stream) do
      {:ok, %{result: "Echo: " <> req.message, sequence: req.sequence, is_final: true}}
    end

    def server_streaming_call(req, _stream) do
      1..10
      |> Stream.map(fn i ->
        %{
          result: "Chunk #{i}: #{req.message}",
          sequence: req.sequence + i,
          is_final: i == 10
        }
      end)
    end

    def client_streaming_call(req_stream, _stream) do
      total =
        Enum.reduce(req_stream, 0, fn item, acc ->
          acc + item.sequence
        end)

      {:ok, %{result: "Sum: #{total}", sequence: total, is_final: true}}
    end

    def bidirectional_streaming_call(req_stream, _stream) do
      Stream.map(req_stream, fn req ->
        %{result: "BidiReply: " <> req.message, sequence: req.sequence * 2, is_final: false}
      end)
    end
  end

  defmodule StreamingClient do
    use SimpleGrpc.Client,
      client_file: "priv/protos/streaming/streaming_service.proto"
  end

  setup_all do
    {:ok, sup_pid} = Bandit.start_link(plug: SimpleGrpc.Plug, port: 0)
    {:ok, {_ip, port}} = ThousandIsland.listener_info(sup_pid)

    on_exit(fn ->
      if Process.alive?(sup_pid), do: Process.exit(sup_pid, :shutdown)
    end)

    %{port: port}
  end

  setup do
    Registry.clear()
    SimpleGrpc.register_service(StreamingServer)
    :ok
  end

  describe "Server Streaming Lazy Consumer (Mint & Plug)" do
    test "Mint: consumes server stream lazily and halts early with Enum.take/2", %{port: port} do
      {:ok, conn} = SimpleGrpc.Client.connect("localhost:#{port}", adapter: :mint)

      req =
        StreamingClient.build_request(:server_streaming_call, %{message: "LazyTest", sequence: 0})

      assert {:ok, stream} = StreamingClient.server_streaming_call(conn, req)

      # Take only first 3 items from a 10-item stream
      first_three = Enum.take(stream, 3)

      assert length(first_three) == 3
      assert Enum.at(first_three, 0).result == "Chunk 1: LazyTest"
      assert Enum.at(first_three, 1).result == "Chunk 2: LazyTest"
      assert Enum.at(first_three, 2).result == "Chunk 3: LazyTest"

      SimpleGrpc.Client.close(conn)
    end

    test "Mint: consumes complete server stream to the end", %{port: port} do
      {:ok, conn} = SimpleGrpc.Client.connect("localhost:#{port}", adapter: :mint)

      req =
        StreamingClient.build_request(:server_streaming_call, %{
          message: "FullTest",
          sequence: 100
        })

      assert {:ok, stream} = StreamingClient.server_streaming_call(conn, req)

      all_chunks = Enum.to_list(stream)
      assert length(all_chunks) == 10
      assert Enum.at(all_chunks, 0).sequence == 101
      assert Enum.at(all_chunks, 9).sequence == 110
      assert Enum.at(all_chunks, 9).is_final == true

      SimpleGrpc.Client.close(conn)
    end

    test "Plug: consumes server stream lazily" do
      {:ok, conn} = SimpleGrpc.Client.connect(SimpleGrpc.Plug, adapter: :plug)

      req =
        StreamingClient.build_request(:server_streaming_call, %{
          message: "PlugStream",
          sequence: 5
        })

      assert {:ok, stream} = StreamingClient.server_streaming_call(conn, req)

      first_two = Enum.take(stream, 2)
      assert length(first_two) == 2
      assert Enum.at(first_two, 0).result == "Chunk 1: PlugStream"
    end
  end

  describe "Client Streaming Progressive Producer (Mint & Plug)" do
    test "Mint: progressively streams request chunks generated by lazy Stream", %{port: port} do
      {:ok, conn} = SimpleGrpc.Client.connect("localhost:#{port}", adapter: :mint)

      # Lazy producer of 5 items
      req_stream =
        1..5
        |> Stream.map(fn i ->
          %{message: "Num #{i}", sequence: i}
        end)

      assert {:ok, resp} = StreamingClient.client_streaming_call(conn, req_stream)
      # 1 + 2 + 3 + 4 + 5 = 15
      assert resp.result == "Sum: 15"
      assert resp.sequence == 15

      SimpleGrpc.Client.close(conn)
    end

    test "Plug: streams client request list" do
      {:ok, conn} = SimpleGrpc.Client.connect(SimpleGrpc.Plug, adapter: :plug)

      req_list = [
        %{message: "A", sequence: 10},
        %{message: "B", sequence: 20}
      ]

      assert {:ok, resp} = StreamingClient.client_streaming_call(conn, req_list)
      assert resp.result == "Sum: 30"
      assert resp.sequence == 30
    end
  end

  describe "Bidirectional Streaming (Mint & Plug)" do
    test "Mint: streams requests and consumes responses", %{port: port} do
      {:ok, conn} = SimpleGrpc.Client.connect("localhost:#{port}", adapter: :mint)

      req_stream =
        1..4
        |> Stream.map(fn i ->
          %{message: "Bidi #{i}", sequence: i}
        end)

      assert {:ok, resp_stream} = StreamingClient.bidirectional_streaming_call(conn, req_stream)

      replies = Enum.to_list(resp_stream)
      assert length(replies) == 4
      assert Enum.at(replies, 0).result == "BidiReply: Bidi 1"
      assert Enum.at(replies, 0).sequence == 2
      assert Enum.at(replies, 3).result == "BidiReply: Bidi 4"
      assert Enum.at(replies, 3).sequence == 8

      SimpleGrpc.Client.close(conn)
    end
  end
end
